-- 방 이름 이전 버전으로 만들어진 개발 DB를 위한 마이그레이션.
ALTER TABLE relay_room ADD COLUMN IF NOT EXISTS name VARCHAR(30);

-- 방 참가자. seat_order는 입장 시점이 아니라 게임 시작 시점에 joined_at 순으로 부여한다 —
-- 시작 전 이탈 때문에 좌석 번호를 재정렬할 일이 없어진다.
CREATE TABLE IF NOT EXISTS relay_participant (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id    BIGINT NOT NULL REFERENCES relay_room (id) ON DELETE CASCADE,
    user_id    BIGINT NOT NULL REFERENCES users (id),
    seat_order INT,
    joined_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    -- 게임 중 이탈 시각. 좌석은 유지되고 그 좌석의 턴은 제한시간 뒤 스킵된다.
    left_at    TIMESTAMP WITH TIME ZONE
);
-- 같은 사람이 한 방에 두 번 들어갈 수 없다. 동시 입장 레이스의 안전망.
CREATE UNIQUE INDEX IF NOT EXISTS uq_relay_participant_user ON relay_participant (room_id, user_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_relay_participant_seat ON relay_participant (room_id, seat_order)
    WHERE seat_order IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_relay_participant_room ON relay_participant (room_id, joined_at);

-- "몇 번째 릴레이 턴을 누가 썼는가"만 기록하는 사이드카. 프롬프트·생성 코드·파일 변경은
-- 방의 어템프트(attempt_turn)에 있고, attempt_turn_ordinal로 이어붙는다.
CREATE TABLE IF NOT EXISTS relay_turn (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id              BIGINT NOT NULL REFERENCES relay_room (id) ON DELETE CASCADE,
    -- 릴레이 진행 인덱스(0-based). 스킵된 턴도 번호를 차지한다.
    turn_index           INT    NOT NULL,
    author_user_id       BIGINT NOT NULL REFERENCES users (id),
    -- 대응하는 attempt_turn.ordinal. 스킵(타임아웃·이탈)이면 NULL이다.
    -- 스킵이 생기면 turn_index와 어긋나므로 둘을 따로 들고 있어야 한다.
    attempt_turn_ordinal INT,
    -- 이 턴 직후의 채점. 결과 원본은 code_run/code_run_case에 있고 여기엔 참조와 집계만 둔다.
    -- 집계를 굳이 복사하는 이유: 점수가 "직전 턴 대비 증가분"이라 턴마다 확정값이 남아야 한다.
    run_id               UUID,
    passed_count         INT,
    total_count          INT,
    started_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at          TIMESTAMP WITH TIME ZONE
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_relay_turn_index ON relay_turn (room_id, turn_index);
