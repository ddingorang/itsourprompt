-- 문제 저장소에서 마지막으로 동기화한 커밋. 한 행(id = 1)만 사용한다.
CREATE TABLE IF NOT EXISTS sync_state (
    id              BIGINT PRIMARY KEY,
    last_commit_sha VARCHAR(64)              NOT NULL,
    synced_at       TIMESTAMP WITH TIME ZONE NOT NULL
);

-- 테스트 분리 마이그레이션의 나머지 절반(problem_test_file 생성부 참고).
-- problem_file에서 테스트를 지워도 problem_test_file로 옮겨오지는 않는다. 동기화는 커밋 SHA가
-- 움직여야 도는데 저장소는 그대로이기 때문이다. SHA를 지워 다음 주기에 전량 재동기화를 강제한다.
-- 테스트가 한 건이라도 들어오면 조건이 거짓이 되어 멈춘다(schema.sql은 부팅마다 실행된다).
-- 문제 저장소에 테스트가 하나도 없으면 매 부팅 재동기화가 도는데, 무해하고 저장소를 고치면 끝난다.
DELETE FROM sync_state WHERE NOT EXISTS (SELECT 1 FROM problem_test_file);

-- 랭킹이 "모두를 같은 자로" 재려면 단가가 SQL 안에 있어야 한다. 진실은 여전히
-- application.yml의 llm.pricing이고 이 테이블은 부팅 때 동기화되는 사본이다
-- (problem을 GitLab에서 동기화해 두는 것과 같은 관계).
-- 모델당 한 행이고 이력은 두지 않는다 — 과거 시점 재현은 attempt_llm_call.cost에 이미 박혀 있다.
CREATE TABLE IF NOT EXISTS model_price (
    model        VARCHAR(100) PRIMARY KEY,
    input        DECIMAL(12,6) NOT NULL,  -- 100만 토큰당 USD
    cached_input DECIMAL(12,6),           -- NULL이면 input 단가를 적용한다
    output       DECIMAL(12,6) NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

-- 랭킹은 문제 하나의 제출을 전부 훑는다. attempt.problem_id에는 FK만 있고 인덱스가 없었다
-- (PostgreSQL은 FK에 인덱스를 자동 생성하지 않는다).
CREATE INDEX IF NOT EXISTS idx_attempt_problem_status ON attempt (problem_id, status);
-- 자격 판정이 (attempt_id, turn_ordinal, status)로 SUCCEEDED 실행을 찾는다.
CREATE INDEX IF NOT EXISTS idx_code_run_attempt_turn_status ON code_run (attempt_id, turn_ordinal, status);

-- 릴레이 게임 방 하나. 여러 사람이 한 문제를 정해진 순서대로 이어 푼다.
-- 코드 진화(프롬프트·생성 코드·파일 변경·채점)는 attempt_id가 가리키는 어템프트가 담당하고,
-- 이 테이블은 방·순서·진행 단계만 들고 있다. 자세한 판단은 docs/relay-game-plan.md 참고.
CREATE TABLE IF NOT EXISTS relay_room (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 방장이 붙이는 방 이름. 개설 API는 필수로 받지만, 이름 도입 전에 만들어진 행이
    -- 있어 컬럼은 NULL을 허용한다(아래 마이그레이션 참고). 화면이 방 번호로 대신한다.
    name               VARCHAR(30),
    problem_id         BIGINT      NOT NULL REFERENCES problem (id),
    host_user_id       BIGINT      NOT NULL REFERENCES users (id),
    -- 게임 시작 시점에 만든다. WAITING 동안은 NULL이다.
    attempt_id         BIGINT      REFERENCES attempt (id),
    status             VARCHAR(30) NOT NULL,
    total_laps         INT         NOT NULL,
    max_participants   INT         NOT NULL,
    -- 시작 시 확정한 참가자 수. 이후 이탈해도 좌석 수는 변하지 않는다.
    seat_count         INT,
    -- 릴레이 진행 인덱스. 좌석은 seat_count로 나눈 나머지, 바퀴는 몫이다.
    -- 좌석과 바퀴를 따로 저장하면 둘이 어긋날 수 있어 단일 카운터에서 파생한다.
    current_turn_index INT         NOT NULL DEFAULT 0,
    turn_deadline      TIMESTAMP WITH TIME ZONE,
    -- 진행 중인 채점 run. 워커 결과 이벤트를 이 값으로 방에 되돌려 잇는다.
    current_run_id     UUID,
    -- 시작 스켈레톤의 채점. 첫 주자의 점수(증가분)를 재는 기준선이다 — 스켈레톤이 이미
    -- 통과시키는 테스트가 있으면 기준선 없이는 첫 주자 점수가 부풀려진다.
    -- 시작 시점에 비동기로 요청하므로 결과가 오기 전까지 passed/total은 NULL이다.
    baseline_run_id    UUID,
    baseline_passed    INT,
    baseline_total     INT,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    started_at         TIMESTAMP WITH TIME ZONE,
    finished_at        TIMESTAMP WITH TIME ZONE
);
CREATE INDEX IF NOT EXISTS idx_relay_room_status ON relay_room (status, created_at DESC);
